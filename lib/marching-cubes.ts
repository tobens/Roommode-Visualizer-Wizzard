const EDGE_CORNERS: [number, number][] = [
  [0, 1],
  [1, 2],
  [2, 3],
  [3, 0],
  [4, 5],
  [5, 6],
  [6, 7],
  [7, 4],
  [0, 4],
  [1, 5],
  [2, 6],
  [3, 7],
]

/**
 * Extracts a closed, indexed 3D triangle mesh (with smooth vertex normals) from a room's
 * scalar volume grid using Marching Cubes with 1-cell boundary padding so isosurfaces cap
 * cleanly along outer walls, floor, ceiling, and arbitrary L-shape / polygon cutouts.
 */
export function extractIsosurface(
  volume: HeatmapVolume,
  isoLevel: number,
  mode: 'above' | 'below',
): IsosurfaceMeshData {
  const { grid, values } = volume
  const { nx, ny, nz, dx, dy, dz, originX, originY, H, cellToVoxel } = grid
  const px = nx + 2
  const py = ny + 2
  const pz = nz + 2
  const totalPadded = px * py * pz

  // Coordinate lookup tables for padded axes (ghost borders sit flush on room outer bounds)
  const xs = new Float32Array(px)
  xs[0] = originX
  for (let i = 1; i <= nx; i++) xs[i] = originX + (i - 0.5) * dx
  xs[nx + 1] = originX + nx * dx

  const ys = new Float32Array(py)
  ys[0] = originY
  for (let j = 1; j <= ny; j++) ys[j] = originY + (j - 0.5) * dy
  ys[ny + 1] = originY + ny * dy

  const zs = new Float32Array(pz)
  zs[0] = 0
  for (let k = 1; k <= nz; k++) zs[k] = (k - 0.5) * dz
  zs[nz + 1] = H

  // Build padded scalar field where values > 0 are INSIDE the isosurface
  // and values < 0 are OUTSIDE the isosurface.
  const span = Math.max(1e-3, volume.max - volume.min)
  const boundaryCapBias = -Math.max(1e-3, span * 0.004)
  const polygonWallBias = -Math.max(0.05, span * 0.14)
  const field = new Float32Array(totalPadded)
  const isBoxBoundary = new Uint8Array(totalPadded)

  for (let k = 0; k < pz; k++) {
    const iz = k - 1
    const zEdge = k === 0 || k === nz + 1
    for (let j = 0; j < py; j++) {
      const iy = j - 1
      const yEdge = j === 0 || j === ny + 1
      for (let i = 0; i < px; i++) {
        const ix = i - 1
        const xEdge = i === 0 || i === nx + 1
        const pIdx = i + px * (j + py * k)
        if (xEdge || yEdge || zEdge) {
          field[pIdx] = boundaryCapBias
          isBoxBoundary[pIdx] = 1
          continue
        }
        const vIdx = cellToVoxel[ix + nx * (iy + ny * iz)]
        if (vIdx < 0) {
          field[pIdx] = polygonWallBias
          continue
        }
        const raw = values[vIdx]
        if (!Number.isFinite(raw)) {
          field[pIdx] = polygonWallBias
          continue
        }
        field[pIdx] = mode === 'above' ? raw - isoLevel : isoLevel - raw
      }
    }
  }

  // Edge vertex cache: 3 edges owned per padded cell (+X = 0, +Y = 1, +Z = 2)
  const edgeCache = new Int32Array(totalPadded * 3)
  edgeCache.fill(-1)

  const posList: number[] = []
  const idxList: number[] = []
  let vertexCount = 0

  // Cube corner offsets in padded grid (px, py, pz)
  const strideY = px
  const strideZ = px * py

  const cxArr = new Int32Array(8)
  const cyArr = new Int32Array(8)
  const czArr = new Int32Array(8)
  const cIdxArr = new Int32Array(8)
  const cValArr = new Float32Array(8)
  const edgeVerts = new Int32Array(12)

  const getEdgeVertex = (c0: number, c1: number, localEdge: number): number => {
    // Map local cube edge to unique cell + axis in edgeCache
    let cellI = 0
    let cellJ = 0
    let cellK = 0
    let axis = 0
    if (localEdge === 0 || localEdge === 2 || localEdge === 4 || localEdge === 6) {
      axis = 0
      const baseCorner = localEdge === 0 ? 0 : localEdge === 2 ? 3 : localEdge === 4 ? 4 : 7
      cellI = cxArr[baseCorner]
      cellJ = cyArr[baseCorner]
      cellK = czArr[baseCorner]
    } else if (localEdge === 1 || localEdge === 3 || localEdge === 5 || localEdge === 7) {
      axis = 1
      const baseCorner = localEdge === 3 ? 0 : localEdge === 1 ? 1 : localEdge === 7 ? 4 : 5
      cellI = cxArr[baseCorner]
      cellJ = cyArr[baseCorner]
      cellK = czArr[baseCorner]
    } else {
      axis = 2
      const baseCorner = localEdge === 8 ? 0 : localEdge === 9 ? 1 : localEdge === 10 ? 2 : 3
      cellI = cxArr[baseCorner]
      cellJ = cyArr[baseCorner]
      cellK = czArr[baseCorner]
    }

    const cacheSlot = (cellI + px * (cellJ + py * cellK)) * 3 + axis
    const existing = edgeCache[cacheSlot]
    if (existing !== -1) return existing

    const v0 = cValArr[c0]
    const v1 = cValArr[c1]
    const denom = v1 - v0
    const t = Math.abs(denom) > 1e-8 ? Math.max(0, Math.min(1, -v0 / denom)) : 0.5

    // Three.js world coordinates: X = room x, Y = height z, Z = room y
    const x0 = xs[cxArr[c0]]
    const y0 = ys[cyArr[c0]]
    const z0 = zs[czArr[c0]]
    const x1 = xs[cxArr[c1]]
    const y1 = ys[cyArr[c1]]
    const z1 = zs[czArr[c1]]

    const wx = x0 + t * (x1 - x0)
    const wy = z0 + t * (z1 - z0)
    const wz = y0 + t * (y1 - y0)

    posList.push(wx, wy, wz)
    const vId = vertexCount++
    edgeCache[cacheSlot] = vId
    return vId
  }

  for (let k = 0; k < pz - 1; k++) {
    for (let j = 0; j < py - 1; j++) {
      for (let i = 0; i < px - 1; i++) {
        const p0 = i + px * (j + py * k)
        const p1 = p0 + 1
        const p3 = p0 + strideY
        const p2 = p3 + 1
        const p4 = p0 + strideZ
        const p5 = p4 + 1
        const p7 = p4 + strideY
        const p6 = p7 + 1

        cIdxArr[0] = p0
        cIdxArr[1] = p1
        cIdxArr[2] = p2
        cIdxArr[3] = p3
        cIdxArr[4] = p4
        cIdxArr[5] = p5
        cIdxArr[6] = p6
        cIdxArr[7] = p7

        let cubeIndex = 0
        for (let c = 0; c < 8; c++) {
          const val = field[cIdxArr[c]]
          cValArr[c] = val
          if (val >= 0) cubeIndex |= 1 << c
        }

        const edgeMask = EDGE_TABLE[cubeIndex]
        if (edgeMask === 0) continue

        cxArr[0] = i
        cyArr[0] = j
        czArr[0] = k
        cxArr[1] = i + 1
        cyArr[1] = j
        czArr[1] = k
        cxArr[2] = i + 1
        cyArr[2] = j + 1
        czArr[2] = k
        cxArr[3] = i
        cyArr[3] = j + 1
        czArr[3] = k
        cxArr[4] = i
        cyArr[4] = j
        czArr[4] = k + 1
        cxArr[5] = i + 1
        cyArr[5] = j
        czArr[5] = k + 1
        cxArr[6] = i + 1
        cyArr[6] = j + 1
        czArr[6] = k + 1
        cxArr[7] = i
        cyArr[7] = j + 1
        czArr[7] = k + 1

        for (let e = 0; e < 12; e++) {
          if (edgeMask & (1 << e)) {
            const [c0, c1] = EDGE_CORNERS[e]
            edgeVerts[e] = getEdgeVertex(c0, c1, e)
          }
        }

        const tris = TRI_TABLE[cubeIndex]
        for (let t = 0; tris[t] !== -1; t += 3) {
          const ia = edgeVerts[tris[t]]
          const ib = edgeVerts[tris[t + 1]]
          const ic = edgeVerts[tris[t + 2]]
          idxList.push(ia, ib, ic)
        }
      }
    }
  }

  const positions = Float32Array.from(posList)
  const indices = Uint32Array.from(idxList)
  const normals = new Float32Array(positions.length)

  // Accumulate area-weighted smooth vertex normals from indexed triangles
  for (let t = 0; t < indices.length; t += 3) {
    const ia = indices[t]
    const ib = indices[t + 1]
    const ic = indices[t + 2]
    const a3 = ia * 3
    const b3 = ib * 3
    const c3 = ic * 3

    const ax = positions[a3]
    const ay = positions[a3 + 1]
    const az = positions[a3 + 2]
    const e1x = positions[b3] - ax
    const e1y = positions[b3 + 1] - ay
    const e1z = positions[b3 + 2] - az
    const e2x = positions[c3] - ax
    const e2y = positions[c3 + 1] - ay
    const e2z = positions[c3 + 2] - az

    const nxV = e1y * e2z - e1z * e2y
    const nyV = e1z * e2x - e1x * e2z
    const nzV = e1x * e2y - e1y * e2x

    normals[a3] += nxV
    normals[a3 + 1] += nyV
    normals[a3 + 2] += nzV
    normals[b3] += nxV
    normals[b3 + 1] += nyV
    normals[b3 + 2] += nzV
    normals[c3] += nxV
    normals[c3 + 1] += nyV
    normals[c3 + 2] += nzV
  }

  for (let v = 0; v < vertexCount; v++) {
    const o = v * 3
    const x = normals[o]
    const y = normals[o + 1]
    const z = normals[o + 2]
    const len = Math.hypot(x, y, z)
    if (len > 1e-12) {
      normals[o] = x / len
      normals[o + 1] = y / len
      normals[o + 2] = z / len
    } else {
      normals[o + 1] = 1
    }
  }

  return {
    positions,
    normals,
    indices,
    vertexCount,
    indexCount: indices.length,
  }
}
